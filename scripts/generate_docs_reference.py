"""
Write the generated reference pages of the documentation:

    docs/reference/tools.md       every tool CONDUCTOR can call, from tool_schemas.py
    docs/reference/providers.md   every model option, from provider_catalog.yaml

Run after changing either source:

    python scripts/generate_docs_reference.py

`tests/test_docs_reference.py` fails while a page is out of date, so the
reference never drifts from what the app actually offers.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "llm_agent"))

from agent import catalog  # noqa: E402
from agent.providers.schema import to_json_schema_tools  # noqa: E402
from agent.tool_schemas import TOOLS  # noqa: E402

OUT = ROOT / "docs" / "reference"
HEADER = ("<!-- Generated by scripts/generate_docs_reference.py from {source}. "
          "Do not edit by hand: change the source and run the script. -->\n\n")

# Every tool belongs to one group; a new tool must be placed here (the test says so).
TOOL_GROUPS = {
    "Reading the grid and the data": [
        "locate_network_element", "get_current_timestamp", "advance_timestamp", "get_current_conditions",
        "get_element_timeseries", "get_data_quality"],
    "Security at one moment": [
        "run_rsa", "simulate_contingency", "simulate_all_contingencies", "compute_violation_attribution",
        "compare_results"],
    "Over time, scenarios and risk": [
        "scan_rsa_over_time", "find_worst_case_timestamp", "scan_scenarios", "run_probabilistic_rsa",
        "compute_historical_risk"],
    "Optimisation and flexibility": [
        "optimize_flexibility", "optimize_contingency", "optimize_robust_flexibility",
        "compute_flexibility_envelope", "compute_hosting_capacity"],
    "Key performance indicators": ["evaluate_kpis", "forecast_kpis"],
    "What-if proposals": ["edit_proposal", "compare_networks"],
    "Settings": ["set_load_power_factor", "set_generator_model", "set_unit_costs", "rename_elements"],
}


def _md(text) -> str:
    """One line of table-safe Markdown."""
    return " ".join(str(text or "").split()).replace("|", "\\|")


def _type(schema: dict) -> str:
    kind = schema.get("type", "")
    if kind == "array":
        return f"list of {_type(schema.get('items') or {}) or 'values'}"
    if schema.get("enum"):
        return " / ".join(f"`{v}`" for v in schema["enum"])
    return {"string": "text", "number": "number", "integer": "whole number", "boolean": "true/false",
            "object": "object"}.get(kind, kind)


def tools_page() -> str:
    tools = {t["function"]["name"]: t["function"] for t in to_json_schema_tools(TOOLS)}
    placed = {name for names in TOOL_GROUPS.values() for name in names}
    groups = dict(TOOL_GROUPS)
    rest = sorted(set(tools) - placed)
    if rest:
        groups["Other"] = rest
    out = [HEADER.format(source="llm_agent/agent/tool_schemas.py"),
           "# Tool reference\n\n",
           "Everything CONDUCTOR can do, it does through these tools: you ask in plain language and it "
           "chooses the tool and its arguments. You never call them yourself, but knowing them tells you "
           "what can be asked, and which arguments a question can set (\"at 18:00\", \"with loads at "
           "120 %\", \"on proposal dc_bus9\", \"with a 90 % line limit\").\n\n",
           "Most studies also take the arguments in [Shared arguments](#shared-arguments).\n\n"]
    for group, names in groups.items():
        out.append(f"- [{group}](#{_anchor(group)}): " + ", ".join(f"[`{n}`](#{n})"
                                                            for n in names if n in tools) + "\n")
    shared = _shared_parameters(tools)
    for group, names in groups.items():
        out.append(f"\n## {group}\n")
        for name in names:
            if name not in tools:
                continue
            fn = tools[name]
            out.append(f"\n### `{name}`\n\n{_md(fn.get('description'))}\n")
            props = (fn.get("parameters") or {}).get("properties") or {}
            required = set((fn.get("parameters") or {}).get("required") or [])
            own = {k: v for k, v in props.items() if k not in shared}
            if own:
                out.append("\n| Argument | Type | Meaning |\n| --- | --- | --- |\n")
                for key, spec in own.items():
                    req = " (required)" if key in required else ""
                    out.append(f"| `{key}`{req} | {_type(spec)} | {_md(spec.get('description'))} |\n")
            common = [k for k in props if k in shared]
            if common:
                out.append("\nAlso takes: " + ", ".join(f"`{k}`" for k in common) + ".\n")
    out.append("\n## Shared arguments\n\nArguments many studies take, with the same meaning everywhere.\n\n"
               "| Argument | Type | Meaning |\n| --- | --- | --- |\n")
    for key, spec in shared.items():
        out.append(f"| `{key}` | {_type(spec)} | {_md(spec.get('description'))} |\n")
    return "".join(out)


def _shared_parameters(tools: dict) -> dict:
    """Arguments with the same description in at least four tools."""
    seen: dict[str, list] = {}
    for fn in tools.values():
        for key, spec in ((fn.get("parameters") or {}).get("properties") or {}).items():
            seen.setdefault(key, []).append(spec)
    return {k: specs[0] for k, specs in sorted(seen.items())
            if len(specs) >= 4 and len({_md(s.get("description")) for s in specs}) == 1}


def _anchor(title: str) -> str:
    keep = "".join(c for c in title.lower() if c.isalnum() or c in " -")
    return keep.replace(" ", "-")


def _limits(limits: dict | None) -> str:
    if not limits:
        return "—"
    parts = [f"{limits[k]:,} {label}" for k, label in (("rpm", "requests/min"), ("tpm", "tokens/min"),
                                                        ("rpd", "requests/day")) if limits.get(k) is not None]
    text = ", ".join(parts)
    if limits.get("note"):
        text = f"{text}. {_md(limits['note'])}" if text else _md(limits["note"])
    text = text or "—"
    if limits.get("verified"):
        text += f" ({limits['verified']}"
        text += f", [source]({limits['source_url']})" if limits.get("source_url") else ""
        text += ")"
    return text


def providers_page() -> str:
    data = catalog.catalog()
    out = [HEADER.format(source="llm_agent/provider_catalog.yaml"),
           "# Model options\n\n",
           "Every option the launch screen offers, as the catalog describes it. Limits and terms change "
           "often: each figure says whether the provider states it (*official*), someone else reports it "
           "(*third_party*) or it could not be found in the provider's documentation (*unverified*), with "
           "its source. Check your provider's console for your own limits.\n\n",
           f"> {_md(data.get('free_tier_notice'))}\n"]
    tiers = data.get("tiers") or {}
    for tier in catalog.TIERS:
        options = catalog.options(data, tier)
        if not options:
            continue
        out.append(f"\n## {tiers.get(tier, {}).get('label', tier.title())}\n\n"
                   f"{_md(tiers.get(tier, {}).get('caption'))}\n")
        for o in options:
            out.append(f"\n### {o['display_name']}\n\n")
            if o.get("signup_note"):
                out.append(f"**What you need:** {_md(o['signup_note'])}\n\n")
            steps = o.get("setup_steps") or []
            if steps:
                # The app's steps end "Paste it below": on this page, the launch screen.
                steps = [re.sub(r"\bbelow\b", "on the launch screen", s) if s.startswith("Paste") else s
                         for s in steps]
                out.append("**Getting started**\n\n" + "".join(f"{n}. {s}\n" for n, s in enumerate(steps, 1))
                           + "\n")
            if o.get("default_model"):
                out.append(f"**Default model:** `{o['default_model']}`\n\n")
            if o.models:
                out.append("| Model | Context | Limits |\n| --- | --- | --- |\n")
                for m in o.models:
                    ctx = f"{m['context_window']:,} tokens" if m.get("context_window") else "—"
                    note = " · advanced, few questions a day" if m.get("advanced") else ""
                    out.append(f"| `{m['id']}`{note} | {ctx} | {_limits(m.get('limits'))} |\n")
                out.append("\n")
            if o.get("account_limits"):
                out.append(f"**Limits (per account):** {_limits(o.get('account_limits'))}\n\n")
            if o.get("discovery") and o["discovery"] != "static" and not o.models:
                out.append("**Models:** listed live on the launch screen.\n\n")
            if o.get("data_policy_summary"):
                link = f" ([terms]({o['data_policy_url']}))" if o.get("data_policy_url") else ""
                out.append(f"**Data:** {_md(o['data_policy_summary'])}{link}\n\n")
            if o.get("last_verified"):
                out.append(f"*Last verified {o['last_verified']}.*\n")
    return "".join(out)


PAGES = {"tools.md": tools_page, "providers.md": providers_page}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, build in PAGES.items():
        (OUT / name).write_text(build(), encoding="utf-8")
        print(f"wrote {OUT / name}")


if __name__ == "__main__":
    main()
